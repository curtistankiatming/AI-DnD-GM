'use strict';
const test=require('node:test'), assert=require('node:assert/strict'), http=require('node:http');
const fs=require('node:fs/promises'), os=require('node:os'), path=require('node:path');
const {createNewGame,buildView}=require('../src/engine');
const N=require('../src/narrator');
const {createLocalAI}=require('../src/local-ai');
test('narration uses the shared AI service only when enabled and falls back without changing game facts',{timeout:15000},async(t)=>{
  let mode='ok';const requests=[];
  const server=http.createServer((req,res)=>{let raw='';req.on('data',b=>raw+=b);req.on('end',()=>{requests.push({path:req.url,body:JSON.parse(raw)});if(mode==='error'){res.writeHead(503);res.end('offline');}else{res.writeHead(200,{'Content-Type':'application/json'});res.end(JSON.stringify({choices:[{finish_reason:'stop',message:{content:'Rain settles on the ward-bell. Your companions wait beside you.'}}]}));}});});
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'briarwatch-narrator-'));
  t.after(async()=>{await new Promise(r=>server.close(r));await fs.rm(dir,{recursive:true,force:true});});
  const ai=createLocalAI({configPath:path.join(dir,'ai.json')});
  const baseUrl=`http://127.0.0.1:${server.address().port}/v1`;
  const s=createNewGame({classId:'wizard'}),v=buildView(s);const facts=()=>JSON.stringify({player:s.player,party:s.party,story:s.story,world:s.world});const before=facts();
  await ai.save({enabled:true,model:'local-mock',baseUrl,narration:false});
  assert.equal((await N.narrate(s,v,{type:'opening'},[],null,ai)).source,'deterministic');assert.equal(requests.length,0,'Narration is opt-in.');
  await ai.save({enabled:true,model:'local-mock',baseUrl,narration:true});
  const good=await N.narrate(s,v,{type:'opening'},[],null,ai);assert.equal(good.source,'ai');assert.match(good.text,/Rain settles/);assert.equal(requests[0].path,'/v1/chat/completions');assert.equal(requests[0].body.model,'local-mock');
  assert.equal(facts(),before);
  mode='error';const fallback=await N.narrate(s,v,{type:'opening'},[],null,ai);assert.equal(fallback.source,'deterministic-fallback');assert.ok(fallback.text.length>0);assert.equal(facts(),before);
  const count=requests.length;await N.narrate(s,v,{type:'buy'},[],null,ai);assert.equal(requests.length,count,'Transactions must not call a model.');
});
